"""Brand files of GEMsMAP and its workspaces, generated from the masters in logo/ and one definition of the gem.

    python tools/brand/make_brand.py        (needs Pillow: pip install -r tools/docs/requirements.txt)

The gem (8 nodes, 15 edges; see docs/brand/README.md) is drawn here as vectors, so it stays sharp at every
size and can switch palettes on dark backgrounds. Written files:

    docs/brand/gemsmap-mark.svg                      the gem alone, display weights, adapts to dark backgrounds
    public/favicon.svg, docs/assets/brand/favicon.svg   favicon weights, adapts to dark backgrounds
    docs/assets/brand/gemsmap-mark-{light,dark}.svg  documentation header (UI weights, one palette each)
    docs/brand/gemsmap-logo{,-dark,-mono}.png        wordmark of logo/gemsmap-logo.png + the vector gem
    docs/brand/{cobragui,mapbuilder,templates}-logo{,-dark}.png
                                                     the workspace logos (logo/<name>-logo.png) on transparency
    docs/brand/templates-logo-horizontal{,-dark}.png the stacked Templates logo set side by side
    public/brand/{cobragui,mapbuilder,templates}-logo.png
                                                     the same, small, for each workspace's header row; the
                                                     stacked Templates logo becomes horizontal there

src/ui/BrandMark.tsx draws the same gem in the app's top bar: keep its NODES, EDGES and weights in step.
"""
import colorsys
from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]

# ------------------------------------------------------------------ the gem
# Unit coordinates. In the 1920 × 1080 masters one unit is 2 px and node B sits at (1517, 264).
NODES = {'A': (-90, 0), 'B': (0, 0), 'C': (90, 0), 'D': (-157, 77), 'E': (-75, 77), 'F': (75, 77), 'G': (157, 77), 'H': (0, 250)}
# Edges coloured like a flux map: (edge, light-background colour, dark-background colour). Pale edges first,
# so the strong ones lie on top. On dark backgrounds strong edges are the brightest and pale ones fade.
EDGES = [
    ('AE', '#f3cada', '#6b3a4a'), ('CF', '#ffbbbc', '#6e3a3c'), ('FH', '#ffbbbc', '#6e3a3c'), ('BF', '#9e9bfe', '#3a3880'),
    ('AB', '#7e7fff', '#4a48a0'), ('EH', '#736eeb', '#5b59b8'), ('AD', '#4c49f6', '#7471ff'), ('GH', '#4c49f6', '#7471ff'),
    ('BC', '#1800ad', '#8f8cff'), ('BE', '#ff5757', '#ff6b6b'), ('CG', '#ff3131', '#ff4d55'), ('DH', '#f24e50', '#f2606a'),
]
GIRDLE = ['DE', 'EF', 'FG']
INK = {
    'light': {'girdle': '#000000', 'ring': '#000000', 'node': '#262626'},
    'dark': {'girdle': '#ededed', 'ring': '#ffffff', 'node': '#dcdcdc'},
}
# Optical sizes: node radius (outer edge of the ring), ring, coloured edge and girdle widths, in units.
WEIGHTS = {
    'display': {'r': 16, 'ring': 3.4, 'edge': 7, 'girdle': 3.2},  # ≥ 96 px, as drawn in the master
    'ui': {'r': 24, 'ring': 5, 'edge': 13, 'girdle': 6},  # 20–48 px: documentation header, app top bar
    'favicon': {'r': 28, 'ring': 5.5, 'edge': 17, 'girdle': 8},  # 16–32 px
}
ABOUT = ('GEMsMAP mark: a gem cut from a metabolic network. Nodes = metabolites; edges = reactions on the diverging '
         'flux scale (red / blue, paler = smaller |flux|); girdle in ink. Generated by tools/brand/make_brand.py.')


def mark_svg(size: str, palette: str, note: str, square: bool = False) -> str:
    """palette: 'light', 'dark' or 'auto' (light, switching to dark with prefers-color-scheme)."""
    w = WEIGHTS[size]
    r = w['r']
    width, height = 314 + 2 * r, 250 + 2 * r
    x0, y0 = -157 - r, -r
    if square:
        y0 -= (width - height) / 2
        height = width
    f = lambda v: f'{v:g}'

    def css(theme: str) -> str:
        ink = INK[theme]
        edges = ''.join(f'.{k}{{stroke:{light if theme == "light" else dark}}}' for k, light, dark in EDGES)
        return edges + f'.g{{stroke:{ink["girdle"]}}}.n{{fill:{ink["node"]};stroke:{ink["ring"]}}}'

    style = css('dark') if palette == 'dark' else css('light')
    if palette == 'auto':
        style += f'\n    @media (prefers-color-scheme:dark){{{css("dark")}}}'
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{f(x0)} {f(y0)} {f(width)} {f(height)}" width="{f(width)}" height="{f(height)}">',
           f'  <!-- {ABOUT} {note} -->',
           '  <title>GEMsMAP</title>',
           f'  <style>{style}</style>',
           '  <g stroke-linecap="round">']
    for k, _, _ in EDGES:
        (x1, y1), (x2, y2) = NODES[k[0]], NODES[k[1]]
        out.append(f'    <line class="{k}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke-width="{f(w["edge"])}"/>')
    for k in GIRDLE:
        (x1, y1), (x2, y2) = NODES[k[0]], NODES[k[1]]
        out.append(f'    <line class="g" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke-width="{f(w["girdle"])}"/>')
    out.append('  </g>')
    out.append(f'  <g class="n" stroke-width="{f(w["ring"])}">')
    out += [f'    <circle cx="{x}" cy="{y}" r="{f(r - w["ring"] / 2)}"/>' for x, y in NODES.values()]
    out += ['  </g>', '</svg>']
    return '\n'.join(out) + '\n'


def draw_gem(size, origin, scale, theme, mono=False, ss=4) -> Image.Image:
    """The gem at display weights on a transparent layer of `size`, node B at `origin`, `scale` px per unit."""
    layer = Image.new('RGBA', (size[0] * ss, size[1] * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    w, ink = WEIGHTS['display'], INK[theme]
    pts = {k: ((origin[0] + x * scale) * ss, (origin[1] + y * scale) * ss) for k, (x, y) in NODES.items()}

    def segment(k, colour, width):
        px = width * scale * ss
        a, b = pts[k[0]], pts[k[1]]
        d.line([a, b], fill=colour, width=round(px))
        for x, y in (a, b):  # round caps
            d.ellipse([x - px / 2, y - px / 2, x + px / 2, y + px / 2], fill=colour)

    for k, light, dark in EDGES:
        segment(k, ink['girdle'] if mono else light if theme == 'light' else dark, w['edge'])
    for k in GIRDLE:
        segment(k, ink['girdle'], w['girdle'])
    rad, ring = w['r'] * scale * ss, w['ring'] * scale * ss
    for x, y in pts.values():
        d.ellipse([x - rad, y - rad, x + rad, y + rad], fill=ink['node'], outline=ink['ring'], width=round(ring))
    return layer.resize(size, Image.LANCZOS)


def crop(im: Image.Image, margin: float) -> Image.Image:
    box = im.getchannel('A').point(lambda a: 255 if a > 25 else 0).getbbox()
    m = round(margin * (box[2] - box[0]))
    return im.crop((max(0, box[0] - m), max(0, box[1] - m), min(im.width, box[2] + m), min(im.height, box[3] + m)))


def resize(im: Image.Image, width=None, height=None) -> Image.Image:
    w, h = (width, round(im.height * width / im.width)) if width else (round(im.width * height / im.height), height)
    return im.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA')  # premultiplied: no dark fringes


# ------------------------------------------------------------------ GEMsMAP logo
def gemsmap_logo(master: Image.Image, theme: str, mono=False) -> Image.Image:
    src = master.convert('RGB')
    px = src.load()
    # in the master the tip of the snake's tail is cut off by a 9 px gap (y 781–789): join it to the tail
    if sum(px[1085, 785]) > 700 and sum(px[1085, 779]) < 300 and sum(px[1085, 792]) < 300:
        d = ImageDraw.Draw(src)
        d.rectangle([1080, 779, 1089, 791], fill=(0, 0, 0))
        d.line([(1079, 779), (1079, 791)], fill=(128, 128, 128))
        d.line([(1090, 779), (1090, 791)], fill=(128, 128, 128))
    # the wordmark is neutral ink: its coverage becomes alpha (#262626 counts as solid)
    alpha = src.convert('L').point(lambda v: 0 if 255 - v < 8 else min(255, round((255 - v) / 0.85)))
    keep = Image.new('L', src.size, 0)
    keep.paste(255, (0, 0, 1150, src.height))  # right of x = 1150 is the gem, redrawn below
    ink = (0, 0, 0) if theme == 'light' else (237, 237, 237)
    out = Image.new('RGBA', src.size, ink + (0,))
    out.putalpha(ImageChops.multiply(alpha, keep))
    out.alpha_composite(draw_gem(src.size, (1517, 264), 2, theme, mono))
    return resize(crop(out, 0.03), width=1600)


# ------------------------------------------------------------------ workspace logos (COBRAGUI, Map Builder, Templates)
@lru_cache(maxsize=None)
def on_dark(r8: int, g8: int, b8: int) -> tuple:
    """A logo colour for dark backgrounds, at the same hue and saturation: a colour too dark to read there (navy)
    is brightened in proportion to its strength on white; every other colour keeps its own lightness, so the
    brand colours stay recognisable."""
    r, g, b = r8 / 255, g8 / 255, b8 / 255
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    target = max(luma, 0.12 + 0.30 * (1 - luma))
    if target == luma:
        return r, g, b
    h, _, sat = colorsys.rgb_to_hls(r, g, b)
    lo, hi = 0.0, 1.0
    for _ in range(14):
        mid = (lo + hi) / 2
        rr, gg, bb = colorsys.hls_to_rgb(h, mid, sat)
        lo, hi = (mid, hi) if 0.2126 * rr + 0.7152 * gg + 0.0722 * bb < target else (lo, mid)
    return colorsys.hls_to_rgb(h, (lo + hi) / 2, sat)


def lift(master: Image.Image, theme: str) -> Image.Image:
    """White becomes transparent. Neutral ink (text, snake, nodes, grey edges, monitor frame) keeps its coverage
    (light ink on dark backgrounds); colours keep their hue. On light backgrounds that is colour-to-alpha, exact
    on white. On dark backgrounds each coloured stroke is first un-blended from white (its pure colour taken from
    the strongest coloured pixel within 2 px) and then recoloured by on_dark(). Neutral and coloured pixels blend
    by saturation, so compression noise in a grey area never flips single pixels between the two."""
    src = master.convert('RGB')
    box = src.convert('L').point(lambda v: 255 if v < 247 else 0).getbbox()
    src = src.crop(box)
    dark = theme == 'dark'
    pixels = list(src.get_flattened_data() if hasattr(src, 'get_flattened_data') else src.getdata())
    # strength of the coloured pixels (distance from white) and its local maximum: a stroke's own colour
    strength = Image.new('L', src.size)
    strength.putdata([round((1 - min(p) / 255) * 255) if max(p) - min(p) > 50 else 0 for p in pixels])
    peaks = strength.filter(ImageFilter.MaxFilter(5))
    peak = list(peaks.get_flattened_data() if hasattr(peaks, 'get_flattened_data') else peaks.getdata())
    ink = 237 / 255 if dark else 0.0
    data = []
    for i, (r8, g8, b8) in enumerate(pixels):
        r, g, b = r8 / 255, g8 / 255, b8 / 255
        mn, mx = min(r, g, b), max(r, g, b)
        a_c = 1 - mn
        if a_c < 0.03:
            data.append((0, 0, 0, 0))
            continue
        wc = max(0.0, min(1.0, (mx - mn - 0.06) / 0.14))
        a_n = 1 - (0.2126 * r + 0.7152 * g + 0.0722 * b)
        if dark:
            a_n = a_n ** 0.75  # grey strokes stay legible on a dark background
            a_max = max(peak[i] / 255, a_c)
            pure = [max(0.0, min(1.0, 1 - (1 - c) * a_max / a_c)) for c in (r, g, b)]
            colour = on_dark(*(round(c * 31) * 255 // 31 for c in pure))
            cov = a_c / a_max
        else:
            colour = [max(0.0, min(1.0, 1 - (1 - c) / a_c)) for c in (r, g, b)]
            cov = a_c
        a_o = (1 - wc) * a_n + wc * cov
        mix = lambda k: round(max(0.0, min(1.0, ((1 - wc) * a_n * ink + wc * cov * colour[k]) / max(a_o, 1e-6))) * 255)
        data.append((mix(0), mix(1), mix(2), round(a_o * 255)))
    out = Image.new('RGBA', src.size)
    out.putdata(data)
    return crop(out, 0.02)


def horizontal(stacked: Image.Image) -> Image.Image:
    """A stacked logo (word above, gem below) set side by side for a header row, where the word would be too
    small: the gem at full height, the word at 40 % of it, centred beside it."""
    alpha = stacked.getchannel('A')
    rows = [alpha.crop((0, y, stacked.width, y + 1)).getextrema()[1] for y in range(stacked.height)]
    top_end = next(y for y in range(stacked.height) if rows[y] > 25)
    gap = next(y for y in range(top_end, stacked.height - 6) if all(v <= 25 for v in rows[y:y + 6]))  # first empty band
    word = crop(stacked.crop((0, 0, stacked.width, gap)), 0)
    gem = crop(stacked.crop((0, gap, stacked.width, stacked.height)), 0)
    word = resize(word, height=round(gem.height * 0.40))
    space = round(gem.height * 0.14)
    out = Image.new('RGBA', (gem.width + space + word.width, gem.height), (0, 0, 0, 0))
    out.alpha_composite(gem, (0, 0))
    out.alpha_composite(word, (gem.width + space, (gem.height - word.height) // 2))
    return crop(out, 0.02)


def write(path: str, content):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, str):
        p.write_text(content, encoding='utf-8', newline='\n')
    else:
        content.save(p, optimize=True)
    print(f'  {path}' + ('' if isinstance(content, str) else f'  {content.width}x{content.height}'))


def main():
    print('gem (vector)')
    write('docs/brand/gemsmap-mark.svg', mark_svg('display', 'auto', 'Display weights; dark palette on dark backgrounds.'))
    favicon = mark_svg('favicon', 'auto', 'Favicon weights (16–32 px); dark palette on dark backgrounds.', square=True)
    write('public/favicon.svg', favicon)
    write('docs/assets/brand/favicon.svg', favicon)
    write('docs/assets/brand/gemsmap-mark-light.svg', mark_svg('ui', 'light', 'Documentation header on light backgrounds (UI weights).'))
    write('docs/assets/brand/gemsmap-mark-dark.svg', mark_svg('ui', 'dark', 'Documentation header on dark backgrounds (UI weights).'))
    print('GEMsMAP logo (logo/gemsmap-logo.png)')
    master = Image.open(ROOT / 'logo' / 'gemsmap-logo.png')
    write('docs/brand/gemsmap-logo.png', gemsmap_logo(master, 'light'))
    write('docs/brand/gemsmap-logo-dark.png', gemsmap_logo(master, 'dark'))
    write('docs/brand/gemsmap-logo-mono.png', gemsmap_logo(master, 'light', mono=True))
    # docs: the logo as drawn (light / dark); app header: 120 px high, shown at 32 px
    for name, docs_height, stacked in [('cobragui', 450, False), ('mapbuilder', 450, False), ('templates', 600, True)]:
        print(f'{name} logo (logo/{name}-logo.png)')
        master = Image.open(ROOT / 'logo' / f'{name}-logo.png')
        light = lift(master, 'light')
        write(f'docs/brand/{name}-logo.png', resize(light, height=docs_height))
        write(f'docs/brand/{name}-logo-dark.png', resize(lift(master, 'dark'), height=docs_height))
        write(f'public/brand/{name}-logo.png', resize(horizontal(light) if stacked else light, height=120))
        if stacked:  # documentation cards, next to the horizontal logos of the other workspaces
            write(f'docs/brand/{name}-logo-horizontal.png', resize(horizontal(light), height=240))
            write(f'docs/brand/{name}-logo-horizontal-dark.png', resize(horizontal(lift(master, 'dark')), height=240))


if __name__ == '__main__':
    main()
